DEFAULT_SIZE = 100.0     # altura da caixa em unidades (10 mm)
DEFAULT_TRACKING = 10.0
DEFAULT_LINE_STEP = 145.0
SPACE_WIDTH = 42.0


def _parse(spec: str):
    """'largura: x,y x,y; x,y' -> (largura, [traços])"""
    width_s, strokes_s = spec.split(":", 1)
    strokes = []
    for part in strokes_s.split(";"):
        pts = []
        for pair in part.split():
            x_s, y_s = pair.split(",")
            pts.append((float(x_s), float(y_s)))
        if len(pts) >= 2:
            strokes.append(pts)
    return float(width_s), strokes


def _glyph(ch: str):
    """Retorna (largura, traços) do caractere, compondo acentos se preciso."""
    if ch in _FONT_RAW:
        return _parse(_FONT_RAW[ch])
    if ch in _COMPOSE:
        base, accent = _COMPOSE[ch]
        width, strokes = _parse(_FONT_RAW[base])
        extra = _ACCENTS.get(accent)
        if extra:
            strokes = strokes + [[(float(x), float(y)) for x, y in extra]]
        return width, strokes
    if ch in _ACCENTS:
        return 40.0, [[(float(x), float(y)) for x, y in _ACCENTS[ch]]]
    return None


def char_available(ch: str) -> bool:
    return ch in _FONT_RAW or ch in _COMPOSE or ch in _ACCENTS


def text_strokes(text: str, size: float = DEFAULT_SIZE,
                 tracking: float = DEFAULT_TRACKING):
    """Converte texto em traços na posição de origem (canto superior esquerdo).

    Retorna (traços, largura_total, altura_total).
    Vários \n criam várias linhas.
    """
    scale = max(1.0, float(size)) / 100.0
    track = float(tracking) * scale
    lines = text.split("\n")
    all_strokes = []
    max_w = 0.0
    for li, line in enumerate(lines):
        pen_x = 0.0
        base_y = li * DEFAULT_LINE_STEP * scale
        for ch in line:
            if ch == " ":
                pen_x += (SPACE_WIDTH + track) * scale
                continue
            g = _glyph(ch)
            if g is None:
                # espaço estreito para caracteres desconhecidos
                pen_x += (SPACE_WIDTH + track) * scale
                continue
            width, strokes = g
            for stroke in strokes:
                all_strokes.append(
                    [(pen_x + x * scale, base_y + y * scale) for x, y in stroke])
            pen_x += (width + track) * scale
        max_w = max(max_w, pen_x)
    height = (len(lines) - 1) * DEFAULT_LINE_STEP * scale + 126.0 * scale
    return all_strokes, max_w, height


def measure_text(text: str, size: float = DEFAULT_SIZE,
                 tracking: float = DEFAULT_TRACKING):
    strokes, w, h = text_strokes(text, size, tracking)
    return w, h
